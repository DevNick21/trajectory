#!/usr/bin/env python3
"""Export the AskPicky FastAPI contract and a tiny TypeScript view."""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
for package in ("engine", "core", "parsers", "retrieval", "evaluators", "privacy", "ai"):
    src = ROOT / "packages" / package / "src"
    if str(src) not in sys.path:
        sys.path.insert(0, str(src))

os.environ.setdefault("ASKPICKY_TEST_MODE", "1")


def _write_json(path: Path, schema: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(schema, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _write_ts(path: Path, schema: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(schema, indent=2, sort_keys=True)
    path.write_text(
        "/* Auto-generated by scripts/export_openapi.py. Do not edit by hand. */\n"
        f"export const openApiSchema = {payload} as const;\n\n"
        "export type OpenApiSchema = typeof openApiSchema;\n"
        "export type ApiPath = keyof OpenApiSchema['paths'];\n"
        "export type ApiMethod<P extends ApiPath> = keyof OpenApiSchema['paths'][P];\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Export AskPicky OpenAPI schema.")
    parser.add_argument("--out", type=Path, required=True, help="JSON output path.")
    parser.add_argument("--ts-out", type=Path, help="Optional TypeScript output path.")
    args = parser.parse_args()

    from askpicky.api.app import create_app

    schema = create_app().openapi()
    _write_json(args.out, schema)
    if args.ts_out:
        _write_ts(args.ts_out, schema)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
